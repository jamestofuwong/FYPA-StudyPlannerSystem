/**
 * Writes the facts of the project that can be read straight from the source code into docs/ai/generated/*.md.
 * The hand-written documents link to these files instead of copying the lists, so they cannot go stale.
 *
 *   npm run docs:facts          write the files
 *   npm run docs:facts -- --check   fail if a file on disk differs from what the code says now (used in CI)
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'docs', 'ai', 'generated');
const rel = (p: string) => path.relative(ROOT, p).split(path.sep).join('/');
const read = (p: string) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

const HEADER = (name: string, source: string) =>
  `<!-- Generated by \`npm run docs:facts\` from ${source}. Do not edit by hand. -->\n# ${name}\n\n`;

/** All files under `dir` that pass `keep`, skipping build output and dependencies. */
function walk(dir: string, keep: (f: string) => boolean, out: string[] = []): string[] {
  const abs = path.join(ROOT, dir);
  if (!fs.existsSync(abs)) return out;
  for (const e of fs.readdirSync(abs, { withFileTypes: true })) {
    if (['node_modules', '.next', 'dist', 'release', '.venv', '__pycache__', '.git', 'resources', 'test-results'].includes(e.name)) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, keep, out);
    else if (keep(p)) out.push(p.split(path.sep).join('/'));
  }
  return out.sort();
}

// ── 1. The Electron bridge ───────────────────────────────────────────────────────────────────────────────────────────
function bridge(): string {
  const pre = read('electron/preload.ts');
  const main = read('electron/main.ts');

  const rows: string[] = [];
  for (const m of pre.matchAll(/exposeInMainWorld\(\s*["'](\w+)["']\s*,\s*\{([\s\S]*?)\n\}\);/g)) {
    const [, obj, body] = m;
    const keys = [...body.matchAll(/^ {2}(\w+)\s*:/gm)];
    keys.forEach((k, i) => {
      const chunk = body.slice(k.index!, keys[i + 1]?.index ?? body.length);
      const invoke = [...chunk.matchAll(/ipcRenderer\.invoke\(\s*["']([\w-]+)["']/g)].map((x) => `invoke \`${x[1]}\``);
      const on = [...chunk.matchAll(/ipcRenderer\.(?:on|once)\(\s*["']([\w-]+)["']/g)].map((x) => `event \`${x[1]}\``);
      const channel = [...invoke, ...on].join(', ') || 'none (a value)';
      rows.push(`| \`${obj}\` | \`${k[1]}\` | ${channel} |`);
    });
  }

  const handlers = [...main.matchAll(/ipcMain\.handle\(\s*["']([\w-]+)["']/g)].map((m) => m[1]);
  const sent = [...new Set([
    ...[...main.matchAll(/webContents\.send\(\s*["']([\w-]+)["']/g)].map((m) => m[1]),
    ...[...main.matchAll(/broadcast\(\s*["']([\w-]+)["']/g)].map((m) => m[1]),
    ...[...main.matchAll(/sendUpdateStatus\(/g)].map(() => 'updater-status'),
  ])].sort();
  const invoked = new Set([...pre.matchAll(/ipcRenderer\.invoke\(\s*["']([\w-]+)["']/g)].map((m) => m[1]));
  const prefs = /webPreferences:\s*\{([\s\S]*?)\}/.exec(main)?.[1] ?? '';
  const flags = [...prefs.matchAll(/(\w+):\s*(true|false)/g)].map((m) => `\`${m[1]}: ${m[2]}\``);

  return HEADER('Electron bridge (generated)', '`electron/preload.ts` and `electron/main.ts`') +
    'What the page can call. The page sees these objects on `window`. Read [electron-bridge.md](../electron-bridge.md) for the rules.\n\n' +
    '| Object | Function | Channel |\n|---|---|---|\n' + rows.join('\n') + '\n\n' +
    '## Handlers in the main process\n\n' +
    handlers.map((h) => `- \`${h}\`${invoked.has(h) ? '' : ' (no preload function uses it)'}`).join('\n') + '\n\n' +
    '## Events that the main process sends\n\n' + sent.map((s) => `- \`${s}\``).join('\n') + '\n\n' +
    '## Window security flags\n\n' + flags.join(', ') + '\n';
}

// ── 2. Panels (pages of the desktop UI) ───────────────────────────────────────────────────────────────────────────────
async function panels(): Promise<string> {
  const nav = await import('../web/lib/navigation');
  const sectionOf = new Map<string, string>();
  for (const s of nav.NAV_SECTIONS) for (const i of s.items) sectionOf.set(i.id, `${s.label} / ${i.label}`);
  const rows = nav.PANEL_IDS.map((id: string) => {
    const page = `web/app/(pages)/${id}/page.tsx`;
    return `| \`${id}\` | \`${nav.PANEL_PATHS[id as keyof typeof nav.PANEL_PATHS]}\` | \`${page}\`${fs.existsSync(path.join(ROOT, page)) ? '' : ' (MISSING)'} | ${sectionOf.get(id) ?? 'not in the sidebar sections'} |`;
  });
  return HEADER('Panels (generated)', '`web/lib/navigation.ts`') +
    'A panel is one page of the desktop UI. A new panel must also be added to the tab bar, the status bar and the icon list. A test checks that all of them agree.\n\n' +
    '| Panel id | Path | Page file | Sidebar |\n|---|---|---|---|\n' + rows.join('\n') + '\n';
}

// ── 3. API routes ────────────────────────────────────────────────────────────────────────────────────────────────────
function routes(): string {
  const section = (label: string, root: string) => {
    const files = walk(root, (f) => /\/route\.ts$/.test(f));
    const rows = files.map((f) => {
      const url = '/' + f.slice(root.indexOf('app/') >= 0 ? root.length - root.split('app/')[1].length - 0 : 0).replace(/^.*?app\//, '').replace(/\/route\.ts$/, '');
      const src = read(f);
      const methods = [...new Set([
        ...[...src.matchAll(/export\s+(?:async\s+)?function\s+(GET|POST|PUT|PATCH|DELETE)\b/g)].map((m) => m[1]),
        ...[...src.matchAll(/export\s+const\s+(GET|POST|PUT|PATCH|DELETE)\b/g)].map((m) => m[1]),
      ])];
      const runtime = /export const runtime = ['"](\w+)['"]/.exec(src)?.[1];
      return `| \`${url}\` | ${methods.join(', ') || '?'} | \`${f}\`${runtime ? ` (runtime ${runtime})` : ''} |`;
    });
    return `## ${label}\n\n| URL | Methods | File |\n|---|---|---|\n${rows.join('\n')}\n`;
  };
  return HEADER('API routes (generated)', 'every `route.ts` file') +
    section('Desktop app (web/app/api)', 'web/app/api') + '\n' + section('Student app (student/app/api)', 'student/app/api');
}

// ── 4. Copilot workflows ─────────────────────────────────────────────────────────────────────────────────────────────
// Read from the source text. Importing the registry would load the portal service, which calls the real portal.
function workflows(): string {
  const dir = 'core/services/copilot/workflows';
  const registry = read('core/services/copilot/workflowRegistry.ts');
  const registered = new Set([...registry.matchAll(/^\s+(\w+Workflow),/gm)].map((m) => m[1]));
  const rows: string[] = [];
  for (const f of walk(dir, (x) => x.endsWith('.ts'))) {
    const src = read(f);
    const exported = /export const (\w+Workflow)\b/.exec(src)?.[1];
    const id = /\n  id: '([a-z_]+)'/.exec(src)?.[1];
    if (!exported || !id) continue;
    const description = (/\n  description: '((?:[^'\\]|\\.)*)'/.exec(src)?.[1] ?? '').replace(/\\'/g, "'");
    const paramsBlock = /\n  params: \[([\s\S]*?)\n  \],/.exec(src)?.[1] ?? '';
    const params = [...paramsBlock.matchAll(/name: '(\w+)',[\s\S]*?required: (true|false)/g)].map((m) => `\`${m[1]}\`${m[2] === 'true' ? '*' : ''}`);
    rows.push(`| \`${id}\` | ${params.join(', ') || 'none'} | \`${f}\`${registered.has(exported) ? '' : ' (NOT REGISTERED)'} | ${esc(description)} |`);
  }
  return HEADER('AI Copilot workflows (generated)', 'the files in `core/services/copilot/workflows` and `workflowRegistry.ts`') +
    `${rows.length} workflows. A star marks a required parameter. The description is what the model reads when it routes a question.\n\n` +
    '| Workflow id | Parameters | File | Description |\n|---|---|---|---|\n' + rows.join('\n') + '\n';
}

// ── 5. Environment variables and secrets ─────────────────────────────────────────────────────────────────────────────
function env(): string {
  const dirs = ['core', 'web', 'electron', 'runtime', 'student', 'scripts', 'e2e', 'playwright.config.ts', 'jest.config.js'];
  const files = dirs.flatMap((d) => (d.includes('.') ? [d] : walk(d, (f) => /\.(ts|tsx|js|mjs)$/.test(f) && !/\.d\.ts$/.test(f) && !/\/tests?\//.test(f) && f !== 'scripts/docs-facts.ts' && f !== 'scripts/docs-check.ts')));
  const uses = new Map<string, Set<string>>();
  for (const f of files) {
    if (!fs.existsSync(path.join(ROOT, f))) continue;
    const src = read(f);
    for (const m of src.matchAll(/process\.env\.([A-Z][A-Z0-9_]+)|process\.env\[['"]([A-Z][A-Z0-9_]+)['"]\]/g)) {
      const name = (m[1] ?? m[2])!;
      if (!uses.has(name)) uses.set(name, new Set());
      uses.get(name)!.add(f);
    }
  }
  const rows = [...uses.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([name, fs_]) => {
    const list = [...fs_];
    return `| \`${name}\` | ${list.slice(0, 4).map((f) => `\`${f}\``).join(', ')}${list.length > 4 ? ` and ${list.length - 4} more` : ''} |`;
  });

  const secrets = new Map<string, Set<string>>();
  for (const f of walk('.github/workflows', (x) => /\.ya?ml$/.test(x))) {
    for (const m of read(f).matchAll(/secrets\.([A-Z][A-Z0-9_]+)/g)) {
      if (!secrets.has(m[1])) secrets.set(m[1], new Set());
      secrets.get(m[1])!.add(path.basename(f));
    }
  }
  const srows = [...secrets.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([n, w]) => `| \`${n}\` | ${[...w].map((x) => `\`${x}\``).join(', ')} |`);

  return HEADER('Environment variables and secrets (generated)', 'every `process.env.NAME` read and every `secrets.NAME` in a workflow') +
    'Names only. A value never appears in this repository. Read [config-and-secrets.md](../config-and-secrets.md) for what each one means and where to set it.\n\n' +
    '## Variables that the code reads\n\n| Variable | Read in |\n|---|---|\n' + rows.join('\n') + '\n\n' +
    '## Secrets that the workflows use\n\n| Secret | Workflow |\n|---|---|\n' + srows.join('\n') + '\n';
}

// ── 6. Commands and pipelines ────────────────────────────────────────────────────────────────────────────────────────
function commands(): string {
  const scripts = (file: string) => {
    const pkg = JSON.parse(read(file));
    return Object.entries(pkg.scripts as Record<string, string>).map(([k, v]) => `| \`${k}\` | \`${esc(v.length > 110 ? v.slice(0, 107) + '...' : v)}\` |`).join('\n');
  };
  // The workflow files are read as text (no YAML package is a dependency of the project).
  const wf = walk('.github/workflows', (f) => /\.ya?ml$/.test(f)).map((f) => {
    const text = read(f);
    const name = /^name:\s*(.+)$/m.exec(text)?.[1].replace(/^['"]|['"]$/g, '') ?? path.basename(f);
    const onBlock = /^on:\s*\n((?:[ \t]+.*\n|\n)*)/m.exec(text)?.[1] ?? '';
    const triggers = [...onBlock.matchAll(/^ {2}(\w+):[ \t]*(.*)\n((?: {4,}.*\n)*)/gm)].map((m) => {
      const body = m[2] + '\n' + m[3];
      const branches = /branches:\s*\[([^\]]*)\]/.exec(body)?.[1];
      const tags = /tags:\s*\n\s*-\s*['"]?([^'"\n]+)/.exec(body)?.[1];
      const paths = /paths:/.test(body) ? 'with path filter' : '';
      const bits = [branches && `branches ${branches}`, tags && `tags ${tags}`, paths].filter(Boolean);
      return `${m[1]}${bits.length ? ` (${bits.join('; ')})` : ''}`;
    });
    const jobsBlock = text.slice(text.search(/^jobs:/m));
    const jobs = [...jobsBlock.matchAll(/^ {2}[\w-]+:\s*\n(?: {4}.*\n|\n)*? {4}name:\s*(.+)$/gm)].map((m) => m[1].replace(/\$\{\{.*?\}\}/g, '...').replace(/^['"]|['"]$/g, ''));
    return `| \`${f}\` | ${name} | ${esc(triggers.join('; '))} | ${esc(jobs.join('; '))} |`;
  });
  return HEADER('Commands and pipelines (generated)', '`package.json`, `student/package.json` and `.github/workflows`') +
    '## Root scripts (`npm run <name>`)\n\n| Script | Command |\n|---|---|\n' + scripts('package.json') + '\n\n' +
    '## Student app scripts (run in `student/`)\n\n| Script | Command |\n|---|---|\n' + scripts('student/package.json') + '\n\n' +
    '## GitHub Actions workflows\n\n| File | Name | Starts on | Jobs |\n|---|---|---|---|\n' + wf.join('\n') + '\n';
}

// ── 7. Where things are: services and tests ─────────────────────────────────────────────────────────────────────────
function modules(): string {
  const svc = fs.readdirSync(path.join(ROOT, 'core/services'), { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort();
  const rows = svc.map((d) => {
    const n = walk(`core/services/${d}`, (f) => /\.(ts|py)$/.test(f)).length;
    const doc = fs.existsSync(path.join(ROOT, `core/services/${d}/README.md`)) ? `[README](../../../core/services/${d}/README.md)` : 'none';
    const tests = fs.existsSync(path.join(ROOT, `tests/unit/${d}`)) ? `\`tests/unit/${d}/\`` : '';
    return `| \`core/services/${d}/\` | ${n} | ${doc} | ${tests} |`;
  });
  const repos = walk('core/db/repositories', (f) => f.endsWith('.ts')).map((f) => `- \`${f}\``);
  const migs = fs.readdirSync(path.join(ROOT, 'core/db/prisma/schema/migrations'), { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => `- \`${e.name}\``);
  return HEADER('Modules (generated)', 'the folders under `core/services` and `core/db`') +
    '| Folder | Source files | Module guide | Unit tests |\n|---|---|---|---|\n' + rows.join('\n') + '\n\n' +
    '## Repositories (`core/db/repositories`)\n\n' + repos.join('\n') + '\n\n## Desktop migrations\n\n' + migs.join('\n') + '\n';
}

export async function build(): Promise<Record<string, string>> {
  return {
    'bridge.md': bridge(),
    'panels.md': await panels(),
    'api-routes.md': routes(),
    'copilot-workflows.md': workflows(),
    'env-vars.md': env(),
    'commands-and-pipelines.md': commands(),
    'modules.md': modules(),
  };
}

async function main() {
  const check = process.argv.includes('--check');
  const files = await build();
  let stale = 0;
  fs.mkdirSync(OUT, { recursive: true });
  for (const [name, text] of Object.entries(files)) {
    const file = path.join(OUT, name);
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (check) {
      if (current !== text) { stale++; console.error(`stale: ${rel(file)}  (run: npm run docs:facts)`); }
    } else if (current !== text) {
      fs.writeFileSync(file, text);
      console.log('wrote', rel(file));
    }
  }
  if (check) { if (stale) process.exit(1); console.log('generated facts are up to date'); }
}

if (require.main === module) main().catch((e) => { console.error(e); process.exit(1); });
