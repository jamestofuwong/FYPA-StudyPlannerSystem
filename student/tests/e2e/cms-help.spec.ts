import { test, expect, login } from './helpers/fixtures'

test('FAQ validation, create, edit, reorder and delete publish through to Help', async ({ page, context, db }) => {
  await login(page, '/cms/help/faq')
  const before = (await db.query('SELECT count(*)::int AS n FROM faq_items')).rows[0].n
  await page.getByRole('button', { name: '+ Add FAQ Item' }).click()
  await page.getByRole('button', { name: /Save Changes/ }).click()
  await expect(page.getByText('Question is required', { exact: true })).toBeVisible()
  await page.getByPlaceholder('FAQ question...').fill('E2E synthetic FAQ?')
  await page.getByPlaceholder('FAQ answer...').fill('E2E synthetic answer.')
  await page.getByRole('button', { name: /Save Changes/ }).click()
  await expect(page.getByText('FAQ items saved successfully.')).toBeVisible()
  await page.reload()
  const item = page.getByText('E2E synthetic FAQ?', { exact: true }).locator('../..')
  await item.locator('button[title="Edit"]').click()
  await page.getByPlaceholder('FAQ answer...').fill('E2E edited answer.')
  await item.locator('button[title="Move up"]').click()
  await page.getByRole('button', { name: /Save Changes/ }).click()
  await expect(page.getByText('FAQ items saved successfully.')).toBeVisible()
  const publicPage = await context.newPage()
  await publicPage.goto('/help')
  await publicPage.getByRole('button', { name: 'E2E synthetic FAQ?', exact: true }).click()
  await expect(publicPage.getByText('E2E edited answer.', { exact: true })).toBeVisible()
  await page.bringToFront()
  const changed = page.getByText('E2E synthetic FAQ?', { exact: true }).locator('../..')
  await changed.locator('button[title="Delete"]').click()
  await page.getByRole('button', { name: /Save Changes/ }).click()
  await expect(page.getByText('FAQ items saved successfully.')).toBeVisible()
  expect((await db.query('SELECT count(*)::int AS n FROM faq_items')).rows[0].n).toBe(before)
})

test('contact edits persist after reload and appear on the public help page', async ({ page, context, db }) => {
  await login(page, '/cms/help/contacts')
  const originalVenue = await page.locator('#enq-venue_name').inputValue()
  const originalPhone = await page.locator('#it-telephone').inputValue()
  await page.locator('#enq-venue_name').fill('E2E Student Support')
  const general = page.locator('form').filter({ has: page.locator('#enq-venue_name') })
  await general.getByRole('button', { name: 'Save', exact: true }).click()
  await expect.poll(async () => (await db.query('SELECT venue_name FROM general_enquiries LIMIT 1')).rows[0].venue_name).toBe('E2E Student Support')
  await page.locator('#it-telephone').fill('+6082 000000')
  const it = page.locator('form').filter({ has: page.locator('#it-telephone') })
  await it.getByRole('button', { name: 'Save', exact: true }).click()
  await expect.poll(async () => (await db.query('SELECT telephone FROM it_help_desk LIMIT 1')).rows[0].telephone).toBe('+6082 000000')
  await page.reload()
  await expect(page.locator('#enq-venue_name')).toHaveValue('E2E Student Support')
  const publicPage = await context.newPage()
  await publicPage.goto('/help')
  await expect(publicPage.getByText(/E2E Student Support/)).toBeVisible()
  await expect(publicPage.getByText('+6082 000000', { exact: true })).toBeVisible()
  await page.bringToFront()
  await page.locator('#enq-venue_name').fill(originalVenue)
  await general.getByRole('button', { name: 'Save', exact: true }).click()
  await expect.poll(async () => (await db.query('SELECT venue_name FROM general_enquiries LIMIT 1')).rows[0].venue_name).toBe(originalVenue)
  await page.locator('#it-telephone').fill(originalPhone)
  await it.getByRole('button', { name: 'Save', exact: true }).click()
  await expect.poll(async () => (await db.query('SELECT telephone FROM it_help_desk LIMIT 1')).rows[0].telephone).toBe(originalPhone)
})

test('Heads of Department validates, creates, publishes and removes a synthetic entry', async ({ page, context, db }) => {
  await login(page, '/cms/help/hod')
  await page.getByRole('button', { name: '+ Add Row' }).click()
  await page.getByRole('button', { name: /Save Changes/ }).click()
  await expect(page.getByText('Faculty is required', { exact: true })).toBeVisible()
  await page.getByPlaceholder('Faculty name').fill('E2E Faculty')
  await page.getByPlaceholder('Department name').fill('E2E Department')
  await page.getByPlaceholder('Full name').fill('Synthetic Department Head')
  await page.getByPlaceholder('email@university.edu.au').fill('invalid-email')
  await page.getByRole('button', { name: /Save Changes/ }).click()
  await expect(page.getByText('Invalid email address', { exact: true })).toBeVisible()
  await page.getByPlaceholder('email@university.edu.au').fill('e2e-hod@example.invalid')
  await page.getByRole('button', { name: /Save Changes/ }).click()
  await expect(page.getByText('Heads of Department saved successfully.')).toBeVisible()
  await page.reload()
  await expect(page.getByText('Synthetic Department Head', { exact: true })).toBeVisible()
  const publicPage = await context.newPage()
  await publicPage.goto('/help/heads-of-department')
  await expect(publicPage.getByRole('link', { name: 'e2e-hod@example.invalid' })).toHaveAttribute('href', 'mailto:e2e-hod@example.invalid')
  await page.bringToFront()
  const row = page.getByRole('row').filter({ hasText: 'Synthetic Department Head' })
  await row.getByRole('button', { name: 'Del', exact: true }).click()
  await page.getByRole('button', { name: /Save Changes/ }).click()
  await expect(page.getByText('Heads of Department saved successfully.')).toBeVisible()
  expect((await db.query("SELECT id FROM heads_of_department WHERE email='e2e-hod@example.invalid'")).rowCount).toBe(0)
})
