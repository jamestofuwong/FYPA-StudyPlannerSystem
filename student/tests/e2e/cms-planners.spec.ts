import { test, expect, login, field, refreshedEventually } from './helpers/fixtures'

test('planner CRUD persists placements and elective pool and publishes the planner', async ({ page, context, db }) => {
  await login(page, '/cms/planners/new')
  await page.getByPlaceholder('e.g. Bachelor of Computer Science').fill('E2E Synthetic Degree')
  await page.getByPlaceholder('e.g. BCS', { exact: true }).fill('E2E-PLAN')
  await page.getByPlaceholder('e.g. Artificial Intelligence').fill('E2E Synthetic Major')
  await field(page, 'Intake Month').selectOption('9')
  await field(page, 'Intake Year').fill('2026')
  await page.getByPlaceholder('e.g. Semester 1, Summer Term').fill('Semester 1')
  await page.getByRole('button', { name: '+ Add Semester', exact: true }).click()
  await page.getByPlaceholder('Search units to add...', { exact: true }).fill('COS10009')
  await page.getByRole('button').filter({ hasText: 'COS10009' }).click()
  await page.getByRole('button', { name: '+ Add Slot' }).click()
  await page.getByPlaceholder('Search units to add to pool...').fill('COS10022')
  await page.getByRole('button').filter({ hasText: 'COS10022' }).click()
  await page.getByRole('button', { name: 'Save Planner', exact: true }).click()
  await expect(page).toHaveURL(/\/cms\/planners\/[0-9a-f-]+$/)
  const id = page.url().split('/').pop()!
  expect((await db.query('SELECT count(*)::int AS n FROM template_units WHERE planner_template_id=$1', [id])).rows[0].n).toBe(2)
  expect((await db.query('SELECT count(*)::int AS n FROM elective_group_units e JOIN elective_groups g ON g.id=e.elective_group_id WHERE g.planner_template_id=$1', [id])).rows[0].n).toBe(1)
  await page.reload()
  await expect(page.getByText('COS10009', { exact: true })).toBeVisible()
  await page.getByPlaceholder('e.g. Artificial Intelligence').fill('E2E Updated Major')
  await page.getByRole('button', { name: 'Save Planner', exact: true }).click()
  await expect.poll(async () => (await db.query('SELECT m.name FROM majors m JOIN planner_templates p ON p.major_id=m.id WHERE p.id=$1', [id])).rows[0].name).toBe('E2E Updated Major')
  const publicPage = await context.newPage()
  await publicPage.goto(`/planners/${id}`)
  await expect(publicPage.getByText('E2E Updated Major', { exact: true })).toBeVisible()
  await expect(publicPage.getByRole('link', { name: 'View Introduction to Programming' })).toBeVisible()
  await page.bringToFront()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Delete Planner', exact: true }).click()
  await expect(page).toHaveURL(/\/cms\/planners$/)
  expect((await db.query('SELECT id FROM planner_templates WHERE id=$1', [id])).rowCount).toBe(0)
  await refreshedEventually(publicPage, () => expect(publicPage.getByText(/not found/i).first()).toBeVisible({ timeout: 1000 }))
})

test('planner validation prevents empty course and duplicate semesters/placements', async ({ page, db }) => {
  await login(page, '/cms/planners/new')
  await page.getByRole('button', { name: 'Save Planner', exact: true }).click()
  await expect(page.getByText('Please enter a course name.')).toBeVisible()
  await page.getByPlaceholder('e.g. Semester 1, Summer Term').fill('Semester 1')
  await page.getByRole('button', { name: '+ Add Semester', exact: true }).click()
  await page.getByPlaceholder('e.g. Semester 1, Summer Term').fill('Semester 1')
  await expect(page.getByRole('button', { name: '+ Add Semester', exact: true })).toBeDisabled()
  await page.getByPlaceholder('Search units to add...', { exact: true }).fill('COS10009')
  await page.getByRole('button').filter({ hasText: 'COS10009' }).click()
  await page.getByPlaceholder('Search units to add...', { exact: true }).fill('COS10009')
  await expect(page.getByRole('button').filter({ hasText: 'COS10009' })).toHaveCount(0)
  await page.getByPlaceholder('e.g. Semester 1, Summer Term').fill('Semester 2')
  await page.getByRole('button', { name: '+ Add Semester', exact: true }).click()
  await expect(page.getByPlaceholder('Semester name', { exact: true })).toHaveCount(2)
  await page.locator('button[title="Move up"]').last().click()
  await expect(page.getByPlaceholder('Semester name', { exact: true }).first()).toHaveValue('Semester 2')
  await page.locator('button[title="Move down"]').first().click()
  await page.locator('button[title="Remove semester"]').last().click()
  await expect(page.getByPlaceholder('Semester name', { exact: true })).toHaveCount(1)
})

test('CMS catalogue filters, pagination and delete-cancel preserve existing planners', async ({ page, db }) => {
  await login(page, '/cms/planners')
  const search = page.getByRole('searchbox', { name: 'Search planners by course code, course, major, or intake' })
  await search.fill('not-a-planner')
  await expect(page.getByText('0 planners found')).toBeVisible()
  await page.getByRole('button', { name: 'Clear Filters', exact: true }).click()
  await search.fill('Artificial Intelligence')
  const row = page.locator('tbody tr').first()
  const before = (await db.query('SELECT count(*)::int AS n FROM planner_templates')).rows[0].n
  await row.getByRole('button', { name: 'Delete', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel' }).click()
  expect((await db.query('SELECT count(*)::int AS n FROM planner_templates')).rows[0].n).toBe(before)
})
