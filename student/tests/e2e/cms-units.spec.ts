import { test, expect, login, saveUnit, refreshedEventually } from './helpers/fixtures'

test('unit CRUD persists every detail tab and publishes the result', async ({ page, context, db }) => {
  await login(page, '/cms/units/new')
  await page.getByPlaceholder('e.g. ICT301').fill('TST90001')
  await page.getByPlaceholder('e.g. Advanced Software Engineering').fill('Synthetic E2E Unit')
  await page.getByPlaceholder('Unit description...').fill('Synthetic overview for browser verification.')
  await page.getByRole('button', { name: 'Availability', exact: true }).click()
  await page.getByLabel('February', { exact: true }).check()
  await page.getByLabel('September', { exact: true }).check()
  await page.getByRole('button', { name: 'Learning Outcomes', exact: true }).click()
  await page.getByRole('button', { name: '+ Add Learning Outcome' }).click()
  await page.getByPlaceholder('ULO 1 description...').fill('Explain synthetic test outcomes.')
  await page.getByRole('button', { name: 'Content', exact: true }).click()
  await page.getByRole('button', { name: '+ Add Topic' }).click()
  await page.getByPlaceholder('Topic title...').fill('Synthetic testing topic')
  await page.getByRole('button', { name: 'Assessments', exact: true }).click()
  await page.getByRole('button', { name: '+ Add Assessment' }).click()
  await page.getByPlaceholder('e.g. Exam').fill('Synthetic exam')
  await page.getByPlaceholder('e.g. Individual').fill('Individual')
  await page.getByPlaceholder('e.g. 40', { exact: true }).fill('100')
  await page.getByPlaceholder('1,2,3').fill('1')
  await page.getByRole('button', { name: 'Requisites', exact: true }).click()
  await page.getByPlaceholder('Search by code or name...').first().fill('COS10009')
  await page.getByRole('button').filter({ hasText: 'COS10009' }).click()
  await page.getByPlaceholder('Search by code or name...').nth(1).fill('COS10026')
  await page.getByRole('button').filter({ hasText: 'COS10026' }).click()
  await page.getByPlaceholder('Search by code or name...').nth(2).fill('COS10025')
  await page.getByRole('button').filter({ hasText: 'COS10025' }).click()
  await page.getByRole('button', { name: 'Save Changes', exact: true }).click()
  await expect(page).toHaveURL(/\/cms\/units\/[0-9a-f-]+$/)
  const id = page.url().split('/').pop()!
  const stored = (await db.query('SELECT unit_name, overview FROM units WHERE id=$1', [id])).rows[0]
  expect(stored.unit_name).toBe('Synthetic E2E Unit')
  expect(stored.overview).toContain('Synthetic overview')
  const requisites = await db.query('SELECT c.requisite_type FROM unit_requisite_conditions c JOIN unit_requisite_groups g ON g.id=c.group_id WHERE g.unit_id=$1', [id])
  expect(requisites.rows.map(r => r.requisite_type).sort()).toEqual(['antirequisite', 'corequisite', 'prerequisite'])
  for (const table of ['unit_learning_outcomes', 'unit_content_topics', 'unit_assessments']) {
    expect((await db.query(`SELECT count(*)::int AS n FROM ${table} WHERE unit_id=$1`, [id])).rows[0].n).toBe(1)
  }
  await page.reload()
  await expect(page.getByPlaceholder('Unit description...')).toHaveValue(stored.overview)
  await page.getByPlaceholder('e.g. Advanced Software Engineering').fill('Synthetic E2E Unit Updated')
  await saveUnit(page)
  const publicPage = await context.newPage()
  await publicPage.goto('/units/TST90001')
  await expect(publicPage.getByRole('heading', { level: 1 })).toHaveText('Synthetic E2E Unit Updated')
  await expect(publicPage.getByRole('link', { name: 'COS10009', exact: true })).toBeVisible()
  for (const text of ['Synthetic overview', 'Explain synthetic test outcomes.', 'Synthetic testing topic', 'Synthetic exam']) await expect(publicPage.getByText(text, { exact: false }).first()).toBeVisible()
  await page.goto('/cms/units')
  await page.getByRole('searchbox', { name: 'Search units by code or name' }).fill('TST90001')
  const row = page.getByRole('row').filter({ hasText: 'TST90001' })
  await row.getByRole('button', { name: 'Delete', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel' }).click()
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: 'Delete', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(row).toHaveCount(0)
  expect((await db.query('SELECT id FROM units WHERE id=$1', [id])).rowCount).toBe(0)
  await refreshedEventually(publicPage, () => expect(publicPage.getByRole('heading', { name: 'Page not found' })).toBeVisible({ timeout: 1000 }))
})

